// Vendors Miniflare's `html-rewriter-wasm` (lol-html in WASM, async handlers via asyncify) as
// an ES module usable in browsers and Node: the CommonJS glue reads its WASM synchronously
// from disk at import time; here it gets an async `__instantiate(source)` instead (the host
// passes bytes, a Response or a WebAssembly.Module), `util` is the platform's TextEncoder/
// TextDecoder, and `assert` is a two-line function.   node scripts/vendor-html-rewriter.mjs
import { copyFileSync, mkdirSync, readFileSync, realpathSync } from "node:fs";
import { join, resolve } from "node:path";
import { build } from "esbuild";

const app = resolve(import.meta.dirname, "..");
const pkg = realpathSync(join(app, "node_modules/html-rewriter-wasm"));
const { version } = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8"));
const out = join(app, "vendor/html-rewriter-wasm");
mkdirSync(out, { recursive: true });
copyFileSync(join(pkg, "dist/html_rewriter_bg.wasm"), join(out, "html_rewriter_bg.wasm"));

const TAIL =
  /const path = require\('path'\)\.join\(__dirname, 'html_rewriter_bg\.wasm'\);[\s\S]*module\.exports\.__wasm = wasm;/;
await build({
  entryPoints: [join(pkg, "dist/html_rewriter.js")],
  outfile: join(out, "html_rewriter.js"),
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  logLevel: "warning",
  banner: {
    js: `// GENERATED by scripts/vendor-html-rewriter.mjs from html-rewriter-wasm@${version} (BSD-3-Clause). Do not edit.`,
  },
  plugins: [
    {
      name: "html-rewriter-wasm-esm",
      setup(b) {
        b.onLoad({ filter: /html_rewriter\.js$/ }, (a) => {
          const src = readFileSync(a.path, "utf8");
          if (!TAIL.test(src)) throw new Error("html-rewriter-wasm: WASM loading tail not found");
          return {
            loader: "js",
            contents: src
              .replace(
                "require(String.raw`util`)",
                "{ TextDecoder: globalThis.TextDecoder, TextEncoder: globalThis.TextEncoder }",
              )
              .replace("require(String.raw`./asyncify.js`)", 'require("./asyncify.js")')
              .replace(
                TAIL,
                `module.exports.__instantiate = async (source) => {
  const mod = source instanceof WebAssembly.Module ? source
    : typeof Response !== "undefined" && source instanceof Response ? await WebAssembly.compileStreaming(source)
    : await WebAssembly.compile(source);
  const instance = await WebAssembly.instantiate(mod, imports);
  wasm = instance.exports;
  setWasmExports(wasm);
  module.exports.__wasm = wasm;
};`,
              ),
          };
        });
        b.onLoad({ filter: /asyncify\.js$/ }, (a) => ({
          loader: "js",
          contents: readFileSync(a.path, "utf8").replace(
            'const assert = require("assert");',
            'const assert = Object.assign((value, message) => { if (!value) throw new Error(message ?? "Assertion failed"); }, { strictEqual: (a, b, message) => { if (a !== b) throw new Error(message ?? `Expected ${a} to be ${b}`); } });',
          ),
        }));
      },
    },
  ],
});
console.log(`vendor/html-rewriter-wasm ← html-rewriter-wasm@${version}`);
