// Vendors celld's portable service code (Apache-2.0) as ES modules:
//   CELLD_SRC=/path/to/denoland/celld node scripts/vendor-celld.mjs
// services/kv.js declares `function kvService(host)` for both of celld's engines (its V8
// harness and workerd); webrun-cells is a third host (src/bindings/celld-kv.ts).
import { execSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const src = process.env.CELLD_SRC;
if (!src) throw new Error("set CELLD_SRC to a denoland/celld checkout");
const commit = execSync("git rev-parse HEAD", { cwd: src }).toString().trim();
const out = resolve(import.meta.dirname, "../vendor/celld");
mkdirSync(out, { recursive: true });
const kv = readFileSync(join(src, "crates/celld/js/services/kv.js"), "utf8");
writeFileSync(
  join(out, "kv.js"),
  `// GENERATED by scripts/vendor-celld.mjs from denoland/celld@${commit} crates/celld/js/services/kv.js\n// (Apache-2.0, unchanged apart from the export below). Do not edit.\n${kv}\nexport { kvService };\n`,
);
console.log(`vendor/celld/kv.js ← denoland/celld@${commit.slice(0, 7)}`);

// Queues live inside celld's harness.js: the queue cell, the producer binding (between the
// "---- Queues" and "---- D1" headers) and the consumer-side batch object
// (__celld.__dispatchEntrypointQueue). Both are extracted verbatim and wrapped as
// queueService(host): the host supplies what harness.js gets from the engine.
const harness = readFileSync(join(src, "crates/celld/js/harness.js"), "utf8");
const cut = (from, to) => {
  const a = harness.indexOf(from);
  const b = harness.indexOf(to, a + from.length);
  if (a < 0 || b < 0) throw new Error(`harness.js markers not found: ${from} … ${to}`);
  return harness.slice(a, b);
};
const queues = cut("// ---- Queues ----", "// ---- D1 ----");
const consumer = cut(
  "// A queue batch owns mutable settlement state only while its handler runs.",
  "// Workerd's simple-handler RPC rules",
);
writeFileSync(
  join(out, "queues.js"),
  `// GENERATED by scripts/vendor-celld.mjs from denoland/celld@${commit} crates/celld/js/harness.js
// (Apache-2.0): the Queues section and __celld.__dispatchEntrypointQueue, unchanged, wrapped as
// queueService(host). Do not edit.
export function queueService(host) {
  const { __cell, __queue_policy, __queue_dispatch, __queue_alarm_set_wait, __sc_encode, __sc_decode,
    __cellSweepBatch, __dispatchEntrypointMethodInCurrentEvent } = host;
  const $$btoa = host.btoa;
  const __d = host.debug ?? (() => {});
  const classes = {};
  const __runtimeClass = (name, cls) => { classes[name] = cls; };
  const __celld = {};
${consumer}
${queues}
  return { QueueCell: classes.__Queue, makeQueue: __celld.__makeQueue, dispatchQueue: __celld.__dispatchEntrypointQueue };
}
`,
);
console.log(`vendor/celld/queues.js ← denoland/celld@${commit.slice(0, 7)}`);
