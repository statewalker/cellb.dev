// Builds Miniflare's simulator Durable Objects (TypeScript written for workerd) into
// browser/Node-compatible ES modules for webrun-cells.
//
//   MINIFLARE_SRC=/path/to/workers-sdk/packages/miniflare node scripts/vendor-miniflare.mjs
//
// The output in vendor/miniflare/ is committed, with the source commit in its header, so
// tests and browsers need no workers-sdk checkout. What is reused UNCHANGED: the simulator
// classes and their shared helpers (router, typed SQL, key-value store, blob store,
// timers, validators). What is substituted:
//   node:assert   → src/miniflare-compat/shims/assert.ts
//   node:buffer   → the `buffer` npm package
//   miniflare:*   → the matching files of the checkout
//   workerd globals (IdentityTransformStream, BYOB readAtLeast) → shims/workerd-globals.ts
//   workerd's integer `performance` clock → shims/workerd-performance.ts (bundle-local)
import { execSync } from "node:child_process";
import { realpathSync } from "node:fs";
import { resolve } from "node:path";
import { build } from "esbuild";

const src = process.env.MINIFLARE_SRC;
if (!src) throw new Error("set MINIFLARE_SRC to workers-sdk/packages/miniflare");
// Optional: a workerd checkout, for its TypeScript binding clients (e.g. D1).
const workerdSrc = process.env.WORKERD_SRC;
const workers = resolve(src, "src/workers");
const app = resolve(import.meta.dirname, "..");
const commit = execSync("git rev-parse HEAD", { cwd: src }).toString().trim();
const workerdCommit = workerdSrc
  ? execSync("git rev-parse HEAD", { cwd: workerdSrc }).toString().trim()
  : "";

const aliases = {
  "node:assert": resolve(app, "src/miniflare-compat/shims/assert.ts"),
  "node:buffer": realpathSync(resolve(app, "node_modules/buffer/index.js")), // real path: pnpm resolves its deps from the store
  "miniflare:shared": resolve(workers, "shared/index.worker.ts"),
  "miniflare:zod": resolve(workers, "shared/zod.worker.ts"),
};

const simulators = {
  "kv-namespace": { entry: resolve(workers, "kv/namespace.worker.ts"), from: "miniflare" },
  "d1-database": { entry: resolve(workers, "d1/database.worker.ts"), from: "miniflare" },
};
if (workerdSrc)
  simulators["d1-api"] = {
    entry: resolve(workerdSrc, "src/cloudflare/internal/d1-api.ts"),
    from: "workerd",
  };

const internal = resolve(app, "src/miniflare-compat/shims/workerd-internal.ts");

for (const [name, { entry, from }] of Object.entries(simulators)) {
  const origin =
    from === "workerd"
      ? `cloudflare/workerd@${workerdCommit} ${entry.slice(workerdSrc.length + 1)} (Apache-2.0)`
      : `cloudflare/workers-sdk@${commit} packages/miniflare/${entry.slice(src.length + 1)} (MIT OR Apache-2.0)`;
  await build({
    entryPoints: [entry],
    outfile: resolve(app, `vendor/miniflare/${name}.js`),
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    mainFields: ["module", "main"],
    inject: [
      resolve(app, "src/miniflare-compat/shims/workerd-globals.ts"),
      resolve(app, "src/miniflare-compat/shims/workerd-performance.ts"),
      ...(from === "workerd"
        ? [resolve(app, "src/miniflare-compat/shims/workerd-cloudflare.ts")]
        : []),
    ],
    tsconfigRaw: { compilerOptions: { experimentalDecorators: true } },
    plugins: [
      {
        name: "miniflare-aliases",
        setup(b) {
          b.onResolve(
            { filter: /^(node:assert|node:buffer|miniflare:shared|miniflare:zod)$/ },
            (a) => ({ path: aliases[a.path] }),
          );
          b.onResolve({ filter: /^cloudflare-internal:/ }, () => ({ path: internal }));
          b.onResolve({ filter: /^zod$/ }, () => ({
            path: realpathSync(resolve(app, "node_modules/zod/index.js")),
          }));
        },
      },
    ],
    banner: {
      js: `// GENERATED by scripts/vendor-miniflare.mjs from ${origin}. Do not edit.`,
    },
    legalComments: "inline",
    logLevel: "warning",
  });
  console.log(`vendor/miniflare/${name}.js  ←  ${origin}`);
}
